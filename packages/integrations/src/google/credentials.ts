import { prisma } from "@jarvis/database";
import { encryptCredential, decryptCredential } from "@jarvis/security";
import { GOOGLE_SCOPES } from "./oauth.js";

const PROVIDER = "google";

export async function saveGoogleCredential(
  userId: string,
  refreshToken: string,
  email: string | undefined,
  encryptionMasterKey: string,
): Promise<void> {
  const payload = encryptCredential(refreshToken, encryptionMasterKey);

  const integration = await prisma.integration.upsert({
    where: { userId_provider: { userId, provider: PROVIDER } },
    create: { userId, provider: PROVIDER, status: "connected", externalId: email, metadata: { email, scopes: GOOGLE_SCOPES } },
    update: { status: "connected", externalId: email, metadata: { email, scopes: GOOGLE_SCOPES } },
  });

  // Prisma's generated Bytes type wants a plain Uint8Array<ArrayBuffer>,
  // which Buffer's type declaration doesn't structurally satisfy —
  // re-wrap rather than cast.
  const ciphertext = Uint8Array.from(payload.ciphertext);
  const iv = Uint8Array.from(payload.iv);
  const authTag = Uint8Array.from(payload.authTag);

  await prisma.encryptedCredential.upsert({
    where: { integrationId: integration.id },
    create: { integrationId: integration.id, ciphertext, iv, authTag },
    update: { ciphertext, iv, authTag },
  });
}

export async function getGoogleRefreshToken(userId: string, encryptionMasterKey: string): Promise<string | null> {
  const integration = await prisma.integration.findUnique({
    where: { userId_provider: { userId, provider: PROVIDER } },
    include: { credential: true },
  });
  if (!integration || integration.status !== "connected" || !integration.credential) {
    return null;
  }
  return decryptCredential(
    {
      ciphertext: Buffer.from(integration.credential.ciphertext),
      iv: Buffer.from(integration.credential.iv),
      authTag: Buffer.from(integration.credential.authTag),
    },
    encryptionMasterKey,
  );
}

export async function isGoogleConnected(userId: string): Promise<boolean> {
  const integration = await prisma.integration.findUnique({ where: { userId_provider: { userId, provider: PROVIDER } } });
  return integration?.status === "connected";
}

export async function disconnectGoogle(userId: string): Promise<boolean> {
  const integration = await prisma.integration.findUnique({ where: { userId_provider: { userId, provider: PROVIDER } } });
  if (!integration) return false;
  await prisma.integration.update({ where: { id: integration.id }, data: { status: "disconnected" } });
  await prisma.encryptedCredential.deleteMany({ where: { integrationId: integration.id } });
  return true;
}
